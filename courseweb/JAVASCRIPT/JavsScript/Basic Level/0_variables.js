//* In JavaScript, values and variables are fundamental concepts that form the basis of programming.

//* Values:  A value is a piece of information that a program can work with. 
// It can be a number, text, true/false, or more complex data.

//* Variables: A variable is a container that holds a value. 
// It has a name and can be used to store and manipulate data in a program.

/*  
Naming Convention of Variables :

=> variable name must start with a letter, an underscore(_) or a doller sign.
=> variable names cannot contain spaces.
=> By convention, Javascript variable names are written in camelCase.
=> Variables cannot be the same as reserved keywords sush as "if" or "const".
=> Variables names are case sensitive.
=> Variables names can be as long as you need.
*/

